export const getProductBySlug = (slug) => {
  return productsData.find(p => p.slug === slug || p.id === slug);
};

export const getRelatedProducts = (currentProductId, category, limit = 4) => {
  const sameCategory = productsData.filter(p => p.id !== currentProductId && p.category === category);
  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }
  const otherProducts = productsData.filter(p => p.id !== currentProductId && p.category !== category);
  return [...sameCategory, ...otherProducts].slice(0, limit);
};
